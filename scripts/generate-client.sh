#! /usr/bin/env bash

set -e
set -x

echo "Starting the generate-client script..."

# Detect the operating system
if [[ "$OSTYPE" == "darwin"* ]]; then
    # macOS
    echo "Detected macOS"
    cd backend
    uv run python -c "import app.main; import json; print(json.dumps(app.main.app.openapi()))" > ../openapi.json
    cd ..
    mv openapi.json frontend/
    cd frontend
    npm run generate-client
    npx biome format --write ./src/client
    # Run the patch script
    node ../scripts/patch-autogenerated-client-code.js
elif [[ "$OSTYPE" == "msys" ]] || [[ "$OSTYPE" == "cygwin" ]] || [[ "$OSTYPE" == "win32" ]]; then
    # Windows (Git Bash, Cygwin, or native Windows)
    echo "Detected Windows"
    cd backend
    /mnt/c/miniconda/aibeniq-react/backend/.venv/Scripts/python.exe -c "import app.main; import json; print(json.dumps(app.main.app.openapi()))" > ../openapi.json
    cd ..
    mv openapi.json frontend/
    cd frontend
    cmd.exe /c npm-with-node.bat run generate-client
    cmd.exe /c npm-with-node.bat run format
    # Run the patch script
    cmd.exe /c "set PATH=C:\Users\David Abugaber\AppData\Local\fnm_multishells\10244_1748038819980;%CD%\node_modules\.bin;%PATH% && node ../scripts/patch-autogenerated-client-code.js"
else
    # Linux or other Unix-like systems
    echo "Detected Linux"
    cd backend
    
    # Try to use the running Docker backend container to generate OpenAPI spec
    if docker-compose ps backend | grep -q "Up"; then
        echo "Using running Docker backend container..."
        cd ..
        echo "Generating OpenAPI spec..."
        docker-compose exec -T backend python -c "import app.main; import json; print(json.dumps(app.main.app.openapi()))" > frontend/openapi.json
        echo "✅ OpenAPI spec generated successfully"
        
        cd frontend
        echo ""
        echo "⚠️  Manual steps required on Linux:"
        echo "1. Install Node.js and npm if not already installed"
        echo "2. Run: npm run generate-client"
        echo "3. Run: npx biome format --write ./src/client"
        echo "4. Run: node ../scripts/patch-autogenerated-client-code.js"
        echo ""
        echo "Or, if you have Node.js/npm installed, the script will continue automatically..."
        
        # Check if npm is available locally
        if command -v npm &> /dev/null && command -v node &> /dev/null; then
            echo "✅ Found npm and node, continuing with client generation..."
            npm run generate-client
            npx biome format --write ./src/client
            node ../scripts/patch-autogenerated-client-code.js
            echo "✅ Client generation complete!"
        else
            echo "❌ npm or node not found. Please install Node.js and run the manual steps above."
            echo "OpenAPI spec is ready in frontend/openapi.json"
        fi
    else
        echo "Docker backend not running, trying local Python..."
        # Try different Python commands in order of preference
        if command -v uv &> /dev/null; then
            echo "Using uv..."
            uv run python -c "import app.main; import json; print(json.dumps(app.main.app.openapi()))" > ../openapi.json
        elif [ -f ".venv/bin/python" ]; then
            echo "Using virtual environment Python..."
            .venv/bin/python -c "import app.main; import json; print(json.dumps(app.main.app.openapi()))" > ../openapi.json
        elif command -v python3 &> /dev/null; then
            echo "Using system python3..."
            python3 -c "import app.main; import json; print(json.dumps(app.main.app.openapi()))" > ../openapi.json
        else
            echo "Using system python..."
            python -c "import app.main; import json; print(json.dumps(app.main.app.openapi()))" > ../openapi.json
        fi
        cd ..
        mv openapi.json frontend/
        cd frontend
        
        # Try to use npm if available
        if command -v npm &> /dev/null && command -v node &> /dev/null; then
            npm run generate-client
            npx biome format --write ./src/client
            node ../scripts/patch-autogenerated-client-code.js
            echo "✅ Client generation complete!"
        else
            echo "❌ npm or node not found. Please install Node.js and run manual steps."
        fi
    fi
fi

