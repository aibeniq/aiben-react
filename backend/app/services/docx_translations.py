def translate_docx_header(key: str, language: str = "en", **kwargs) -> str:
    """
    Translate DOCX headers with simple backend translations.

    Args:
        key: Translation key (e.g., "documentEvaluation", "generatedOn")
        language: Target language code
        **kwargs: Format parameters for string substitution (e.g., date, name, email)

    Returns:
        Translated string with parameters substituted
    """
    # Get translation, fallback to English if language not found
    translation = DOCX_TRANSLATIONS.get(key, {}).get(language)
    if not translation:
        translation = DOCX_TRANSLATIONS.get(key, {}).get("en", key)

    # Substitute parameters if provided
    if kwargs:
        try:
            translation = translation.format(**kwargs)
        except KeyError as e:
            print(f"Warning: Missing parameter {e} for translation key '{key}'")

    return translation
