/**
 * Adds help translations to all language resources
 * Falls back to English for any missing language
 */
export const addHelpTranslations = (resources: any) => {
  for (const [langCode, resource] of Object.entries(resources)) {
    if (resource && typeof resource === "object" && "common" in resource) {
      const resourceObj = resource as any
      // Get help translations for this language, fallback to English
      const helpTexts =
        helpTranslations[langCode as keyof typeof helpTranslations] ||
        helpTranslations.en

      // Add or merge help section
      if (!resourceObj.common.help) {
        resourceObj.common.help = helpTexts
      } else {
        // Merge missing keys from helpTexts into existing help section
        for (const [key, value] of Object.entries(helpTexts)) {
          if (!resourceObj.common.help[key]) {
            resourceObj.common.help[key] = value
          }
        }
      }
    }
  }
}
